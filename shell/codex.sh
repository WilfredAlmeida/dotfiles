# shellcheck shell=sh

if [ -n "${DOTFILES_CODEX_HOME:-}" ]; then
  CODEX_HOME=$DOTFILES_CODEX_HOME
elif mkdir -p /persistent/.codex 2>/dev/null && [ -w /persistent/.codex ]; then
  CODEX_HOME=/persistent/.codex
else
  CODEX_HOME=$HOME/.codex
fi
export CODEX_HOME

mkdir -p "$CODEX_HOME" 2>/dev/null || true

# Codex stops looking for project instructions at a Git root. Rebuild its
# global file so the rules above nested repos under /workspaces are not missed.
_dotfiles_root=${DOTFILES_ROOT:-$HOME/.config/coderv2/dotfiles}
_dotfiles_personal_agents=$_dotfiles_root/agents/AGENTS.md
_dotfiles_workspace_agents=${DOTFILES_WORKSPACE_AGENTS:-/workspaces/AGENTS.md}

if [ -s "$_dotfiles_root/agents/codex/AGENTS.md" ]; then
  _dotfiles_personal_agents=$_dotfiles_root/agents/codex/AGENTS.md
fi

if [ -s "$_dotfiles_personal_agents" ] && [ -d "$CODEX_HOME" ]; then
  _dotfiles_agents_tmp=$(mktemp "$CODEX_HOME/.AGENTS.md.XXXXXX") || _dotfiles_agents_tmp=
  if [ -n "$_dotfiles_agents_tmp" ]; then
    if {
      printf '%s\n\n' '<!-- Generated by dotfiles. Do not edit this copy. -->' &&
        printf '%s\n\n' '# Personal instructions' &&
        cat "$_dotfiles_personal_agents" &&
        printf '\n' &&

      if [ -s "$_dotfiles_workspace_agents" ]; then
        printf '\n%s\n\n' '# Workspace instructions' &&
          cat "$_dotfiles_workspace_agents" &&
          printf '\n'
      fi
    } > "$_dotfiles_agents_tmp" &&
      chmod 600 "$_dotfiles_agents_tmp" &&
      mv "$_dotfiles_agents_tmp" "$CODEX_HOME/AGENTS.md"; then
      :
    else
      rm -f "$_dotfiles_agents_tmp"
    fi
  fi
fi

unset _dotfiles_root _dotfiles_personal_agents _dotfiles_workspace_agents _dotfiles_agents_tmp
